function buildSegmentPrompt(userText: string): string {
  return (
    `<|begin_of_text|><|start_header_id|>system<|end_header_id|>\n\n` +
    `${SEGMENT_SYSTEM_PROMPT}<|eot_id|>` +
    `<|start_header_id|>user<|end_header_id|>\n\n` +
    `${userText}<|eot_id|>` +
    `<|start_header_id|>assistant<|end_header_id|>\n\n`
  );
}

function parseSegments(raw: string): { segments: string[]; failed: boolean } {
  const cleaned = raw.replace(/```(?:json)?/g, '').trim();
  const start   = cleaned.indexOf('[');
  const end     = cleaned.lastIndexOf(']');
  if (start === -1 || end === -1 || end < start) return { segments: [], failed: true };
  try {
    const arr     = JSON.parse(cleaned.slice(start, end + 1)) as unknown[];
    const strings = arr.filter((s): s is string => typeof s === 'string' && s.trim().length > 0);
    return { segments: strings, failed: false };
  } catch {
    return { segments: [], failed: true };
  }
}

async function segmentText(userText: string): Promise<string[]> {
  await ensureNlu();
  try {
    const out = await _ctx!.completion({
      prompt:      buildSegmentPrompt(userText),
      n_predict:   200,
      temperature: 0.0,
      stop:        ['<|eot_id|>', '<|end_of_text|>'],
    });
    const { segments, failed } = parseSegments(out.text);
    // failed = JSON parse error → treat full text as one claim (safe fallback)
    // succeeded + empty = SLM found no health content → return [] so NER is skipped
    return failed ? [userText] : segments;
  } catch {
    return [userText];
  }
}

