/**
 * NLU layer — on-device NER using Llama 3.2-1B-Instruct (Q4_K_M).
 *
 * Three-level routing cascade (L1 > L2 > L3):
 *   L1 — text matches a specific item-column question (column-question-map.json)
 *   L2 — text matches a composite/direct source-column description (source-column-descriptions.json)
 *   L3 — direct node-state assignment (feature-node-config.json state labels)
 *
 * Indirect effects (e.g. "drank coffee") are not extracted here — they go to
 * the unmatched vector index for the ReAct agent (Gemma 4B) to handle at
 * insight time.
 *
 * Usage:
 *   await initNlu('/absolute/path/to/Llama-3.2-1B-Instruct.Q4_K_M.gguf');
 *   await warmupNlu();   // call in background at startup — caches system prompt KV
 *   const result = await runNer(db, "I haven't been sleeping well this week");
 *
 * column-question-map.json is generated by:
 *   python -m codebase.backend.export_column_question_map
 */

