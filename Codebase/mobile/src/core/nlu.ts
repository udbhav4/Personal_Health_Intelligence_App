/**
 * Classify user intent using Llama. Always runs on every turn.
 * n_predict=40, temperature=0.0 — output is short structured JSON.
 */
export async function classifyIntent(userText: string): Promise<IntentResult> {
  await ensureNlu();

  const validNodes = new Set(Object.keys(NODE_SCHEMA));
  const nodeList   = Object.keys(NODE_SCHEMA).join(', ');
  const systemPrompt = CLASSIFY_INTENT_SYSTEM_PROMPT.replace('[NODE_LIST]', nodeList);

  // Build prompt: system header + few-shot pairs + actual user turn
  let prompt =
    `<|begin_of_text|><|start_header_id|>system<|end_header_id|>\n\n` +
    `${systemPrompt}<|eot_id|>`;

  for (const msg of CLASSIFY_INTENT_SHOTS) {
    const role = msg.role === 'user' ? 'user' : 'assistant';
    prompt +=
      `<|start_header_id|>${role}<|end_header_id|>\n\n` +
      `${msg.content}<|eot_id|>`;
  }

  prompt +=
    `<|start_header_id|>user<|end_header_id|>\n\n` +
    `${userText}<|eot_id|>` +
    `<|start_header_id|>assistant<|end_header_id|>\n\n`;

  let raw: string;
  try {
    const out = await _ctx!.completion({
      prompt,
      n_predict:   120,
      temperature: 0.0,
      stop:        ['<|eot_id|>', '<|end_of_text|>'],
    });
    raw = out.text;
  } catch {
    return { ...INTENT_FALLBACK };
  }

  try {
    const cleaned = raw.replace(/```(?:json)?/g, '').trim();
    const start   = cleaned.indexOf('{');
    const end     = cleaned.lastIndexOf('}');
    if (start === -1 || end === -1 || end < start) return { ...INTENT_FALLBACK };

    const parsed = JSON.parse(cleaned.slice(start, end + 1)) as Record<string, unknown>;

    const queryNodes = (Array.isArray(parsed.queryNodes) ? parsed.queryNodes as unknown[] : [])
      .filter((n): n is string => typeof n === 'string' && validNodes.has(n))
      .slice(0, 10);

    return {
      hasReport:         Boolean(parsed.hasReport),
      hasQuery:          Boolean(parsed.hasQuery),
      hasTrendQuery:     Boolean(parsed.hasTrendQuery) && Boolean(parsed.hasQuery),
      isSocial:          Boolean(parsed.isSocial),
      isThirdPartyQuery: Boolean(parsed.isThirdPartyQuery),
      queryNodes,
    };
  } catch {
    return { ...INTENT_FALLBACK };
  }
}

