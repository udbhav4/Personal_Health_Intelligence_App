// ── Types ─────────────────────────────────────────────────────────────────────

export interface NluEntity {
  // Exactly one of original_column / source_column is set, or both absent (L3)
  original_column?:  string;         // L1: specific item col (e.g. 'phq_interest')
  source_column?:    string;         // L2: composite or direct col (e.g. 'phq_total')
  node_name:         string;         // validated DBN node
  node_value:        string | null;  // validated state, or null for L1/L2
  raw_value?:        number;         // numeric score before discretization (L1/L2)
  confidence:        number;         // [0, 1]
  raw_text:          string;         // exact user phrase
  summary_text:      string;         // compressed factual note for semantic search
  report_scope?:     'today' | 'week' | 'daily';
  report_date_str?:  string;         // YYYY-MM-DD resolved from raw_date_text
  raw_date_text?:    string;         // exact phrase user used ("last Tuesday", "in March")
}

export interface NluResult {
  entities:   NluEntity[];
  unmatched:  string[];   // segments with no L1/L2/L3 match → ReAct agent handles
  topics:     string[];   // per-segment NER-derived topic keywords; walk-back fills gaps
  raw_output: string;
}

export interface IntentResult {
  hasReport:         boolean;  // message contains personal health info to update
  hasQuery:          boolean;  // asks about user's own health state
  hasTrendQuery:     boolean;  // asks about trends/history/changes over time; only true when hasQuery is also true
  isSocial:          boolean;  // ONLY social — no health content; mutually exclusive with others
  isThirdPartyQuery: boolean;  // question about someone else's health
  queryNodes:        string[]; // validated DBN node names queried (max 10)
}

// ── Schema tables (built once at module load) ─────────────────────────────────

interface NodeConfigEntry {
  state_labels?:       string[];
  description?:        string;
  self_report?:        boolean;
  temporal?:           boolean;
  source_column_bins?: Record<string, unknown>;
}
interface ColumnEntry {
  c:      string;
  n:      string;
  q:      string;
  opts?:  { v: number; l: string }[];
  range?: { min: number; max: number; unit: string };
}

const _nodes  = (nodeConfig as any).nodes as Record<string, NodeConfigEntry>;
const _cqMap  = columnQuestionMap as Record<string, ColumnEntry>;
const _srcDesc = sourceColDescs   as Record<string, string>;

// NODE_SCHEMA — self_report nodes only
interface NodeSchemaEntry { states: string[]; temporal: boolean; }
const NODE_SCHEMA: Record<string, NodeSchemaEntry> = (() => {
  const s: Record<string, NodeSchemaEntry> = {};
  for (const [name, node] of Object.entries(_nodes)) {
    if (!node.self_report) continue;
    const states = node.state_labels ?? [];
    if (states.length) s[name] = { states, temporal: node.temporal ?? true };
  }
  return s;
})();

// SOURCE_COL_TO_NODE — reverse map from source_column_bins keys → node_name
const SOURCE_COL_TO_NODE: Record<string, string> = (() => {
  const m: Record<string, string> = {};
  for (const [name, node] of Object.entries(_nodes)) {
    if (!node.self_report) continue;
    for (const col of Object.keys(node.source_column_bins ?? {})) m[col] = name;
    // node name itself may also be a composite column name (e.g. pain_level)
    m[name] = name;
  }
  return m;
})();

// COMPOSITE_ITEM_COUNT — items per source column for L1 confidence = 1/n
const COMPOSITE_ITEM_COUNT: Record<string, number> = (() => {
  const counts: Record<string, number> = {};
  for (const entry of Object.values(_cqMap)) {
    counts[entry.c] = (counts[entry.c] ?? 0) + 1;
  }
  return counts;
})();

// SENSORLESS_COL_BINS — discretization config per source column (self_report nodes only)
interface ColBinConfig {
  method:       string;
  thresholds?:  number[];          // clinical: raw-value boundaries
  bin_edges?:   number[];          // kmeans: z-score space — not usable without user history
  state_labels: string[];
  state_map?:   Record<string, string>; // col-label → node-label remapping (for mismatched cardinality)
  value_map?:   Record<string, string>; // numeric option code → intermediate label (applied before state_map)
  is_composite?: boolean;              // true only for summed instruments (PHQ-9, GAD-7); guards composite early-return
}
const SENSORLESS_COL_BINS: Record<string, ColBinConfig> = (() => {
  const m: Record<string, ColBinConfig> = {};
  for (const node of Object.values(_nodes)) {
    if (!node.self_report) continue;
    for (const [col, raw] of Object.entries(node.source_column_bins ?? {})) {
      const b = raw as Record<string, unknown>;
      m[col] = {
        method:       typeof b.method === 'string' ? b.method : 'kmeans',
        thresholds:   Array.isArray(b.thresholds)  ? (b.thresholds  as number[]) : undefined,
        bin_edges:    Array.isArray(b.bin_edges)    ? (b.bin_edges   as number[]) : undefined,
        state_labels: Array.isArray(b.state_labels) ? (b.state_labels as string[]) : [],
        state_map:    (b.state_map && typeof b.state_map === 'object' && !Array.isArray(b.state_map))
          ? (b.state_map as Record<string, string>)
          : undefined,
        value_map:    (b.value_map && typeof b.value_map === 'object' && !Array.isArray(b.value_map))
          ? (b.value_map as Record<string, string>)
          : undefined,
        is_composite: typeof b.is_composite === 'boolean' ? b.is_composite : undefined,
      };
    }
  }
  return m;
})();

