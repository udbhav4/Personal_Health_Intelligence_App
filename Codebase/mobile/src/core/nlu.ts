// Keyword gate: words that can only appear in a correction/undo message.
// Plain health reports never contain these. If none present → skip model entirely.
const UNDO_KEYWORDS = [
  'actually', 'wait no', 'i meant', 'i mean ', 'was wrong', 'were wrong',
  'that was', 'that\'s wrong', 'thats wrong', 'not true', 'mistake',
  'wrong,', 'wrong.', 'wrong!', 'incorrect', 'disregard', 'ignore that',
  'forget what', 'undo', 'take back', 'retract', 'correct that',
  'i lied', 'i exaggerated', 'i overstated', 'overstated',
  'looking back', 'on second thought', 'i think i was',
  'i said wrong', 'i told wrong', 'that info was',
];

function hasUndoSignal(text: string): boolean {
  const lower = text.toLowerCase();
  return UNDO_KEYWORDS.some(kw => lower.includes(kw));
}

/** Returns true if the user's message signals intent to undo or correct a previous entry. */
export async function detectUndoIntent(userText: string): Promise<boolean> {
  // Fast gate: no correction keyword → definitely not an undo. Skip model entirely.
  if (!hasUndoSignal(userText)) return false;

  await ensureNlu();
  const prompt =
    `<|begin_of_text|><|start_header_id|>system<|end_header_id|>\n\n` +
    `${UNDO_SYSTEM_PROMPT}<|eot_id|>` +
    `<|start_header_id|>user<|end_header_id|>\n\n` +
    `${userText}<|eot_id|>` +
    `<|start_header_id|>assistant<|end_header_id|>\n\n`;
  try {
    const out = await _ctx!.completion({
      prompt,
      n_predict:   3,
      temperature: 0.0,
      stop:        ['<|eot_id|>', '\n'],
    });
    return out.text.toLowerCase().trimStart().startsWith('yes');
  } catch {
    return false;
  }
}
