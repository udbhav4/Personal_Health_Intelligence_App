// ── Singleton context ──────────────────────────────────────────────────────────

let _ctx:       LlamaContext | null = null;
let _modelPath: string | null       = null;

/**
 * Load the Llama 3.2-1B model. Call once at app startup.
 * n_ctx=8192: the three-level schema injected into the prompt is ~4800 tokens;
 * remaining headroom covers user messages and generated output.
 */
export function setNluPath(modelPath: string): void {
  _modelPath = modelPath;
}

export async function initNlu(modelPath: string): Promise<void> {
  if (_ctx && _modelPath === modelPath) return;
  if (_ctx) { await _ctx.release(); _ctx = null; }
  _modelPath = modelPath;
  try {
    _ctx = await initLlama({
      model:      modelPath,
      use_mlock:  false,
      n_ctx:      4096,
      n_threads:  4,
      n_parallel: 1,
    });
  } catch (e) {
    throw new Error(`nlu load failed [path=${modelPath}]: ${e instanceof Error ? e.message : String(e)}`);
  }
}

/** Reinitialise from stored path if context was evicted by OS. */
export async function ensureNlu(): Promise<void> {
  if (_ctx) return;
  if (!_modelPath) throw new Error('nlu: initNlu() has not been called — no model path stored');
  await initNlu(_modelPath);
}

/**
 * Pre-process the segmentation prompt so its KV cache is warm before the
 * first real runNer() call. Segmentation always runs first, so warming it
 * (not the NER prompt) is what saves latency on first user message.
 */
export async function warmupNlu(): Promise<void> {
  if (!_ctx) return;
  await _ctx.completion({
    prompt:      buildSegmentPrompt(''),
    n_predict:   1,
    temperature: 0.0,
    stop:        ['<|eot_id|>'],
  });
}

export function isNluReady(): boolean { return _ctx !== null; }

export async function releaseNlu(): Promise<void> {
  if (_ctx) { await _ctx.release(); _ctx = null; }
}

