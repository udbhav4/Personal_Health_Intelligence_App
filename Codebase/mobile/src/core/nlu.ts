// ── Output parser ──────────────────────────────────────────────────────────────

/**
 * Parse and validate JSON entity array from raw model output.
 *
 * L1: original_column must be in _cqMap. Confidence overridden to
 *     1 / COMPOSITE_ITEM_COUNT[source_col] — model value ignored.
 * L2: source_column must resolve to a self_report node. node_value must be null.
 * L3: node_value must be a valid state. confidence >= MIN_CONFIDENCE_L3.
 */
function parseEntities(raw: string, now: Date, mode: 'glance' | 'reflect'): NluEntity[] {
  const gates = CONFIDENCE_GATES[mode];
  const cleaned = raw.replace(/```(?:json)?/g, '').trim();
  const start   = cleaned.indexOf('[');
  const end     = cleaned.lastIndexOf(']');
  if (start === -1 || end === -1 || end < start) return [];

  let parsed: unknown[];
  try { parsed = JSON.parse(cleaned.slice(start, end + 1)) as unknown[]; }
  catch { return []; }

  const result: NluEntity[] = [];

  for (const item of parsed) {
    if (typeof item !== 'object' || item === null) continue;
    const e = item as Record<string, unknown>;

    const origCol  = typeof e.original_column === 'string' ? e.original_column : null;
    const srcCol   = typeof e.source_column   === 'string' ? e.source_column   : null;
    const nodeName = typeof e.node_name       === 'string' ? e.node_name       : null;
    const nodeVal  = typeof e.node_value      === 'string' ? e.node_value      : null;
    const rawVal   = typeof e.raw_value       === 'number' ? e.raw_value       : undefined;
    const rawText  = typeof e.raw_text        === 'string' ? e.raw_text        : null;
    const summary  = typeof e.summary_text    === 'string' ? e.summary_text    : null;
    const confRaw  = typeof e.confidence      === 'number' ? e.confidence      : null;

    if (!nodeName || !rawText || !summary) continue;

    const scope = (['today', 'week', 'daily'] as const).find(s => s === e.report_scope);
    const rawDateText = typeof e.raw_date_text === 'string' ? e.raw_date_text : undefined;
    const reportDateStr = rawDateText
      ? (chrono.parseDate(rawDateText, now)?.toISOString().slice(0, 10) ?? undefined)
      : undefined;

    if (origCol !== null) {
      // ── L1 ────────────────────────────────────────────────────────────────
      const entry = _cqMap[origCol];
      if (!entry || !NODE_SCHEMA[entry.n]) continue;
      if ((confRaw ?? 0) < gates.l1) continue;
      const confidence = 1 / (COMPOSITE_ITEM_COUNT[entry.c] ?? 1);
      result.push({
        original_column: origCol,
        node_name: entry.n, node_value: null, raw_value: rawVal,
        confidence, raw_text: rawText, summary_text: summary,
        report_scope: scope, raw_date_text: rawDateText, report_date_str: reportDateStr,
      });

    } else if (srcCol !== null) {
      // ── L2 ────────────────────────────────────────────────────────────────
      const resolvedNode = SOURCE_COL_TO_NODE[srcCol]
        ?? (_nodes[srcCol]?.self_report ? srcCol : null);
      if (!resolvedNode || !NODE_SCHEMA[resolvedNode]) continue;
      if ((confRaw ?? 0) < gates.l2) continue;
      result.push({
        source_column: srcCol,
        node_name: resolvedNode, node_value: null, raw_value: rawVal,
        confidence: confRaw ?? 0.7,
        raw_text: rawText, summary_text: summary,
        report_scope: scope, raw_date_text: rawDateText, report_date_str: reportDateStr,
      });

    } else {
      // ── L3 ────────────────────────────────────────────────────────────────
      const schema = NODE_SCHEMA[nodeName];
      if (!schema || !nodeVal || !schema.states.includes(nodeVal)) continue;
      const confidence = confRaw ?? 0.5;
      if (confidence < gates.l3) continue;
      result.push({
        node_name: nodeName, node_value: nodeVal, raw_value: rawVal,
        confidence, raw_text: rawText, summary_text: summary,
        report_scope: scope, raw_date_text: rawDateText, report_date_str: reportDateStr,
      });
    }
  }

  return result;
}

// ── Helpers ───────────────────────────────────────────────────────────────────

function deduplicateEntities(entities: NluEntity[]): NluEntity[] {
  const seen = new Map<string, NluEntity>();
  for (const ent of entities) {
    const col = ent.original_column ?? ent.source_column ?? ent.node_name;
    const key = `${col}||${ent.report_scope ?? ''}`;
    const existing = seen.get(key);
    if (!existing || ent.confidence > existing.confidence) seen.set(key, ent);
  }
  return [...seen.values()];
}

function toExpiresDate(scope: string | undefined, baseDate: string): string | null {
  if (!scope || scope === 'daily') return null;
  const d = new Date(baseDate + 'T00:00:00'); // local midnight, avoids UTC-minus rollback
  d.setDate(d.getDate() + (scope === 'week' ? 7 : 1));
  return d.toLocaleDateString('sv'); // YYYY-MM-DD local
}

function discretizeClinical(rawVal: number, thresholds: number[], stateLabels: string[]): string | null {
  // thresholds = [min, b1, b2, ..., max]; stateLabels[i] covers [thresholds[i], thresholds[i+1])
  for (let i = 0; i < stateLabels.length - 1; i++) {
    if (rawVal < thresholds[i + 1]) return stateLabels[i];
  }
  return stateLabels[stateLabels.length - 1] ?? null;
}

/**
 * Returns the composite source column (e.g. 'phq_total') for a given item column
 * (e.g. 'phq_sleep'), or the item column itself if no mapping exists.
 * Used by agent.ts completeTurn to pass the correct column to maybeResolveComposite.
 */
export function getCompositeSourceCol(itemCol: string): string {
  return _cqMap[itemCol]?.c ?? itemCol;
}

export function resolveNodeValue(ent: NluEntity): string | null {
  let col: string | null = null;
  if (ent.original_column) {
    const srcCol = _cqMap[ent.original_column]?.c;
    if (!srcCol) return null;
    // Composite instruments (e.g. PHQ-9, GAD-7): item raw_value (0–3) ≠ total score → skip.
    // Guard is now driven by is_composite flag rather than item count, so independent
    // binary questions (pain_level, diabetes_status, etc.) are not blocked.
    const binConf = SENSORLESS_COL_BINS[srcCol];
    if (binConf?.is_composite === true) return null;
    col = srcCol;
  } else if (ent.source_column) {
    col = ent.source_column;
  }

  if (!col) return null;
  const binConf = SENSORLESS_COL_BINS[col];
  if (!binConf) return null;

  const nodeStates = NODE_SCHEMA[ent.node_name]?.states ?? [];

  // Passthrough: raw string IS the node state — apply value_map then state_map if provided
  if (binConf.method === 'passthrough') {
    const rawStr    = typeof ent.raw_value === 'number' ? String(ent.raw_value) : ent.raw_text;
    const afterVMap = binConf.value_map ? (binConf.value_map[rawStr] ?? rawStr) : rawStr;
    const mapped    = binConf.state_map ? (binConf.state_map[afterVMap] ?? afterVMap) : afterVMap;
    return nodeStates.includes(mapped) ? mapped : null;
  }

  // Clinical: if value_map present, apply it first to convert numeric code → label,
  // then either pass straight to state_map (no thresholds) or discretize numerically.
  if (binConf.method === 'clinical') {
    // value_map path: numeric option code → intermediate label → state_map → node state
    if (binConf.value_map && ent.raw_value !== undefined) {
      const rawStr    = String(ent.raw_value);
      const afterVMap = binConf.value_map[rawStr];
      if (afterVMap !== undefined) {
        const mapped = binConf.state_map ? (binConf.state_map[afterVMap] ?? afterVMap) : afterVMap;
        return nodeStates.includes(mapped) ? mapped : null;
      }
    }
    // Threshold path: discretize numeric raw_value, then apply state_map if needed
    if (binConf.thresholds?.length && ent.raw_value !== undefined) {
      const discretized = discretizeClinical(ent.raw_value, binConf.thresholds, binConf.state_labels);
      if (!discretized) return null;
      const mapped = binConf.state_map ? (binConf.state_map[discretized] ?? discretized) : discretized;
      return nodeStates.includes(mapped) ? mapped : null;
    }
  }

  return null;
}

// ── Composite completeness ────────────────────────────────────────────────────

/**
 * After each new L1 item write for a multi-item source column, check whether
 * ≥ 80% of items are now answered within the current turn. If so, compute a
 * partial total score and discretize it, then update node_value on all rows
 * for that (node, turn) with a scaled confidence.
 *
 * Confidence scaling: 0.65 + 0.25 * (answered / total)
 *   4/5 items answered → 0.85;  5/5 → 0.90
 */
export function maybeResolveComposite(db: DB, nodeName: string, sourceCol: string, turnId: string): void {
  const total = COMPOSITE_ITEM_COUNT[sourceCol];
  if (!total || total <= 1) return; // not a composite instrument

  const rows = db.executeSync(
    `SELECT raw_value FROM user_data_sensorless
     WHERE node_name = ? AND turn_id = ? AND is_active = 1
       AND raw_value IS NOT NULL
       AND original_column IN (
         SELECT value FROM json_each(?)
       )`,
    [nodeName, turnId, JSON.stringify(Object.keys(_cqMap).filter(k => _cqMap[k].c === sourceCol))],
  ).rows as { raw_value: number }[];

  const answered = rows.length;
  if (answered === 0 || answered / total < 0.8) return;

  const totalScore = rows.reduce((s, r) => s + Number(r.raw_value), 0);
  const binConf    = SENSORLESS_COL_BINS[sourceCol];
  if (!binConf || binConf.method !== 'clinical' || !binConf.thresholds?.length) return;

  const discretized = discretizeClinical(totalScore, binConf.thresholds, binConf.state_labels);
  if (!discretized) return;

  const nodeStates = NODE_SCHEMA[nodeName]?.states ?? [];
  const mapped     = binConf.state_map ? (binConf.state_map[discretized] ?? discretized) : discretized;
  if (!nodeStates.includes(mapped)) return;

  const confidence = 0.65 + 0.25 * (answered / total);

  db.executeSync(
    `UPDATE user_data_sensorless
     SET node_value = ?, confidence = ?
     WHERE node_name = ? AND turn_id = ? AND is_active = 1
       AND original_column IN (
         SELECT value FROM json_each(?)
       )`,
    [mapped, confidence, nodeName, turnId,
     JSON.stringify(Object.keys(_cqMap).filter(k => _cqMap[k].c === sourceCol))],
  );
}

