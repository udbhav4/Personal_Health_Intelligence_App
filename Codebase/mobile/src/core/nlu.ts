/**
 * Run on-device NER on userText, write all valid entities to
 * user_data_sensorless, and return the result.
 * Returns empty entities without throwing if model is not initialised.
 *
 * @param db           - Open SQLite handle (from openDb()).
 * @param userText     - Raw user message.
 * @param questionText - Question the app asked, if any (audit trail).
 */
export async function runNer(
  db:           DB,
  userText:     string,
  questionText: string = '',
  turnId:       string = '',
  mode:         'glance' | 'reflect' = 'reflect',
  sessionId:    string = '',
): Promise<NluResult> {
  await ensureNlu();

  const now      = new Date();
  const todayIso = now.toISOString().slice(0, 10);
  const ts       = now.toISOString().replace('T', ' ').slice(0, 19);

  // Pass 1: split into individual health claims
  const segments = await segmentText(userText);
  if (segments.length === 0) return { entities: [], unmatched: [], topics: [], raw_output: '' };

  // Pass 2: NER on each segment — each call targets one claim → reliable output
  const rawParts:    string[]    = [];
  const allEntities: NluEntity[] = [];
  const unmatched:   string[]    = [];
  const topicParts:  string[]    = [];

  // Lazy-loaded fallback topic from most recent stored message (walk-back for no-entity segments)
  let fallbackTopic: string | null = null;
  function getFallbackTopic(): string {
    if (fallbackTopic !== null) return fallbackTopic;
    if (!sessionId) return (fallbackTopic = '');
    const row = db.executeSync(
      `SELECT topic FROM chat_messages
       WHERE session_id = ? AND topic IS NOT NULL AND topic != '' AND is_active = 1
       ORDER BY created_at DESC LIMIT 1`,
      [sessionId],
    ).rows[0] as { topic: string } | undefined;
    return (fallbackTopic = row?.topic ?? '');
  }

  for (const segment of segments) {
    let raw: string;
    try {
      const out = await _ctx!.completion({
        prompt:      buildPrompt(segment, todayIso),
        n_predict:   512,
        temperature: 0.1,
        top_p:       0.9,
        stop:        ['<|eot_id|>', '<|end_of_text|>'],
      });
      raw = out.text;
    } catch {
      unmatched.push(segment);
      const fb = getFallbackTopic();
      if (fb) topicParts.push(fb);
      continue;
    }
    rawParts.push(raw);
    const parsed = parseEntities(raw, now, mode);
    if (parsed.length === 0) {
      unmatched.push(segment);
      // No NER match — use most recent stored topic as this segment's topic
      const fb = getFallbackTopic();
      if (fb) topicParts.push(fb);
    } else {
      allEntities.push(...parsed);
      // Topic = summary_text of each entity extracted from this segment
      const segTopic = parsed.map(e => e.summary_text).join(', ');
      topicParts.push(segTopic);
    }
  }

  const entities = deduplicateEntities(allEntities);

  for (const ent of entities) {
    const schema      = NODE_SCHEMA[ent.node_name]!;
    const reportDate  = ent.report_date_str ?? todayIso;
    const expiresDate = toExpiresDate(ent.report_scope, reportDate);
    const mergeMode   = ent.original_column ? 'scale' : 'latest';

    let proactiveSuppressedUntil: string | null = null;
    if (ent.original_column) {
      if (expiresDate) {
        proactiveSuppressedUntil = expiresDate;
      } else {
        const staleDays = STALENESS_DAYS[ent.node_name];
        if (staleDays) {
          const d = new Date(now);
          d.setDate(d.getDate() + staleDays);
          proactiveSuppressedUntil = d.toISOString().slice(0, 10);
        }
      }
    }

    const resolvedNodeValue = ent.node_value ?? resolveNodeValue(ent);

    db.executeSync(
      `INSERT INTO user_data_sensorless
         (timestamp, node_name, original_column, source_column,
          question_text, raw_text, node_value, raw_value,
          confidence, data_source, merge_mode, temporal_flag,
          report_date, expires_date, summary_text, turn_id,
          proactive_suppressed_until, was_proactive, answered)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, 1)`,
      [
        ts,
        ent.node_name,
        ent.original_column ?? null,
        ent.source_column   ?? null,
        questionText        || null,
        userText,
        resolvedNodeValue   ?? null,
        ent.raw_value       ?? null,
        ent.confidence,
        'self_report',
        mergeMode,
        schema.temporal ? 'decaying' : 'persistent',
        reportDate,
        expiresDate,
        ent.summary_text,
        turnId              || null,
        proactiveSuppressedUntil,
      ],
    );

    // For L1 entities belonging to multi-item composites, check if ≥80% is now answered
    if (ent.original_column && turnId) {
      const srcCol = _cqMap[ent.original_column]?.c;
      if (srcCol) maybeResolveComposite(db, ent.node_name, srcCol, turnId);
    }
  }

  // Deduplicate topic parts while preserving order
  const seen = new Set<string>();
  const topics = topicParts.filter(t => { if (seen.has(t)) return false; seen.add(t); return true; });

  return { entities, unmatched, topics, raw_output: rawParts.join('\n---\n') };
}

